  fun analyzeFile(file: File): ImageInspectionResult {
    val length = file.length()
    val bytes = try {
      val maxRead = minOf(length, 10 * 1024 * 1024L).toInt() // Read up to 10 MB for metadata headers
      FileInputStream(file).use { input ->
        val buf = ByteArray(maxRead)
        var totalRead = 0
        while (totalRead < maxRead) {
          val r = input.read(buf, totalRead, maxRead - totalRead)
          if (r == -1) break
          totalRead += r
        }
        if (totalRead < maxRead) buf.copyOf(totalRead) else buf
      }
    } catch (_: Exception) {
      ByteArray(0)
    }

    return analyzeBytes(bytes, file.name, length, file)
  }

  fun analyzeBytes(
    bytes: ByteArray,
    fileName: String,
    totalSizeBytes: Long = bytes.size.toLong(),
    backingFile: File? = null
  ): ImageInspectionResult {
    val evidenceList = mutableListOf<EvidenceItem>()
    var extractedPrompt: String? = null
    var cameraMakeModel: String? = null
    var software: String? = null
    var dateOriginal: String? = null
    var width = 0
    var height = 0

    // 1. Parse EXIF
    if (bytes.isNotEmpty()) {
      try {
        val exif = ExifInterface(ByteArrayInputStream(bytes))
        val make = exif.getAttribute(ExifInterface.TAG_MAKE)
        val model = exif.getAttribute(ExifInterface.TAG_MODEL)
        if (!make.isNullOrBlank() || !model.isNullOrBlank()) {
          cameraMakeModel = "${make.orEmpty()} ${model.orEmpty()}".trim()
        }

        software = exif.getAttribute(ExifInterface.TAG_SOFTWARE)
        dateOriginal = exif.getAttribute(ExifInterface.TAG_DATETIME_ORIGINAL)
        width = exif.getAttributeInt(ExifInterface.TAG_IMAGE_WIDTH, 0)
        height = exif.getAttributeInt(ExifInterface.TAG_IMAGE_LENGTH, 0)

        val userComment = exif.getAttribute(ExifInterface.TAG_USER_COMMENT)
        val desc = exif.getAttribute(ExifInterface.TAG_IMAGE_DESCRIPTION)

        val allExifText = listOfNotNull(software, userComment, desc).joinToString(" ")
        for (kw in KNOWN_AI_GENERATORS) {
          if (allExifText.contains(kw, ignoreCase = true)) {
            evidenceList.add(EvidenceItem("EXIF Metadata", "Mentions '$kw'", EvidenceStrength.STRONG))
          }
        }

        if (userComment != null && (userComment.contains("Steps:", ignoreCase = true) || userComment.contains("Sampler:", ignoreCase = true))) {
          extractedPrompt = userComment
          evidenceList.add(EvidenceItem("EXIF UserComment", "Stable Diffusion generation parameters detected", EvidenceStrength.STRONG))
        }
      } catch (_: Throwable) {
        // Fallback for environments where ExifInterface is not available or throws during class loading
      }
    }

    // 2. Scan byte stream for C2PA, XMP, PNG text chunks, and JPEG markers
    val fileString = String(bytes, StandardCharsets.ISO_8859_1)

    if (software == null) {
      for (sw in EDITING_SOFTWARE) {
        if (fileString.contains(sw, ignoreCase = true)) {
          software = sw
          break
        }
      }
    }

    // C2PA / Content Credentials Detection
    if (fileString.contains("c2pa", ignoreCase = true) || fileString.contains("JUMBF", ignoreCase = true) || fileString.contains("caBX")) {
      evidenceList.add(EvidenceItem("C2PA Content Credentials", "C2PA / JUMBF provenance box present (signature not verified offline)", EvidenceStrength.STRONG))
      if (fileString.contains("trainedAlgorithmicMedia", ignoreCase = true)) {
        evidenceList.add(EvidenceItem("C2PA Action", "digitalSourceType: trainedAlgorithmicMedia", EvidenceStrength.STRONG))
      }
      if (fileString.contains("compositeWithTrainedAlgorithmicMedia", ignoreCase = true)) {
        evidenceList.add(EvidenceItem("C2PA Action", "digitalSourceType: compositeWithTrainedAlgorithmicMedia", EvidenceStrength.STRONG))
      }
    }

    // XMP DigitalSourceType / History
    if (fileString.contains("DigitalSourceType", ignoreCase = true)) {
      if (fileString.contains("trainedAlgorithmicMedia", ignoreCase = true)) {
        evidenceList.add(EvidenceItem("XMP DigitalSourceType", "trainedAlgorithmicMedia", EvidenceStrength.STRONG))
      } else if (fileString.contains("algorithmicMedia", ignoreCase = true)) {
        evidenceList.add(EvidenceItem("XMP DigitalSourceType", "algorithmicMedia", EvidenceStrength.STRONG))
      }
    }

    // PNG Text Chunks (parameters, prompt)
    if (fileName.endsWith(".png", ignoreCase = true) || (bytes.size >= 8 && bytes[0] == 0x89.toByte() && bytes[1] == 0x50.toByte())) {
      val pngChunks = extractPngTextChunks(bytes)
      for ((key, text) in pngChunks) {
        if (key.equals("parameters", ignoreCase = true) || key.equals("prompt", ignoreCase = true) || key.equals("workflow", ignoreCase = true)) {
          extractedPrompt = text
          evidenceList.add(EvidenceItem("PNG Chunk ($key)", "Contains generation prompt / workflow parameters", EvidenceStrength.STRONG))
        } else {
          for (gen in KNOWN_AI_GENERATORS) {
            if (text.contains(gen, ignoreCase = true)) {
              evidenceList.add(EvidenceItem("PNG Chunk ($key)", "References '$gen'", EvidenceStrength.STRONG))
            }
          }
        }
      }
    }

    // Known AI keywords anywhere in raw string
    for (kw in KNOWN_AI_GENERATORS) {
      if (fileString.contains(kw, ignoreCase = true)) {
        val already = evidenceList.any { it.value.contains(kw, ignoreCase = true) }
        if (!already) {
          evidenceList.add(EvidenceItem("Embedded Trace", "Matches generator signature: $kw", EvidenceStrength.STRONG))
        }
      }
    }

    // Dimensions check
    val dimsStr = if (width > 0 && height > 0) "${width}×${height}" else null
    if (width > 0 && height > 0) {
      if (COMMON_AI_DIMENSIONS.contains(width to height) || COMMON_AI_DIMENSIONS.contains(height to width)) {
        evidenceList.add(EvidenceItem("Image Dimensions", "$dimsStr matches standard neural generator aspect", EvidenceStrength.WEAK))
      }
    }

    // Camera presence check
    if (cameraMakeModel == null && !evidenceList.any { it.strength == EvidenceStrength.STRONG }) {
      evidenceList.add(EvidenceItem("Camera Data", "No camera Make/Model found (weak signal)", EvidenceStrength.WEAK))
    }

    // 3. ELA Analysis if backing file is present
    var elaMean = 0f
    var elaMax = 0f
    var elaHotRatio = 0f
    var heatmapFile: File? = null

    if (backingFile != null && backingFile.exists() && backingFile.length() > 0L) {
      try {
        val bmp = android.graphics.BitmapFactory.decodeFile(backingFile.absolutePath)
        if (bmp != null) {
          val tempDir = File(backingFile.parentFile, "ela_heatmaps").apply { if (!exists()) mkdirs() }
          val targetHeatmap = File(tempDir, "${backingFile.nameWithoutExtension}_ela.png")
          val ela = ElaEngine.analyzeBitmap(bmp, targetHeatmap)
          elaMean = ela.meanDifference
          elaMax = ela.maxDifference
          elaHotRatio = ela.hotPixelsRatio
          heatmapFile = ela.heatmapFile
          bmp.recycle()

          if (elaHotRatio > 0.18f) {
            evidenceList.add(EvidenceItem("Error Level Analysis", "High localized compression delta (${String.format("%.1f%%", elaHotRatio * 100f)} hot pixels)", EvidenceStrength.MEDIUM))
          }
        }
      } catch (_: Throwable) {}
    }

    // 4. Verdict Logic
    val hasStrong = evidenceList.any { it.strength == EvidenceStrength.STRONG }
    val hasEditSoftware = software?.let { s -> EDITING_SOFTWARE.any { s.contains(it, ignoreCase = true) } } == true ||
      evidenceList.any { it.sourceField.contains("Error Level") }

    val verdict = when {
      hasStrong -> AiVerdict.STRONG
      hasEditSoftware -> AiVerdict.EDITED
      evidenceList.any { it.strength == EvidenceStrength.WEAK && it.sourceField.contains("Dimensions") } -> AiVerdict.POSSIBLE
      else -> AiVerdict.NONE
    }

    val (verdictTitle, verdictDesc) = when (verdict) {
      AiVerdict.STRONG -> "AI-Generated / AI-Edited Markers Found" to "Direct generation markers, generator software signatures, or C2PA algorithmic provenance tags were detected in the file."
      AiVerdict.EDITED -> "Edited Image (No Direct AI Marker)" to "Image contains editing software traces or compression variances, but no unambiguous generative AI tags."
      AiVerdict.POSSIBLE -> "Possible AI Generation (Weak Signals Only)" to "Image exhibits typical generator aspect dimensions or missing camera metadata, which are weak indicators."
      AiVerdict.NONE -> "No AI Markers Found" to AiInspectorReportBuilder.MANDATORY_HONESTY_TEXT
    }

    return ImageInspectionResult(
      inputName = fileName,
      fileSizeBytes = totalSizeBytes,
      dimensions = dimsStr,
      verdict = verdict,
      verdictTitle = verdictTitle,
      verdictDescription = verdictDesc,
      evidenceList = evidenceList,
      extractedPrompt = extractedPrompt,
      elaScoreMean = elaMean,
      elaScoreMax = elaMax,
      elaHotRatio = elaHotRatio,
      elaHeatmapPath = heatmapFile?.absolutePath,
      cameraMakeModel = cameraMakeModel,
      software = software,
      dateOriginal = dateOriginal
    )
  }

  private fun extractPngTextChunks(bytes: ByteArray): Map<String, String> {
    val results = mutableMapOf<String, String>()
    var pos = 8 // skip 8-byte PNG header
    while (pos + 8 <= bytes.size) {
      val length = ((bytes[pos].toInt() and 0xFF) shl 24) or
        ((bytes[pos + 1].toInt() and 0xFF) shl 16) or
        ((bytes[pos + 2].toInt() and 0xFF) shl 8) or
        (bytes[pos + 3].toInt() and 0xFF)
      val type = String(bytes, pos + 4, 4, StandardCharsets.US_ASCII)

      if (length < 0 || pos + 8 + length > bytes.size) break

      val chunkData = bytes.copyOfRange(pos + 8, pos + 8 + length)
      if (type == "tEXt") {
        val nullIdx = chunkData.indexOf(0.toByte())
        if (nullIdx > 0 && nullIdx < chunkData.size) {
          val key = String(chunkData, 0, nullIdx, StandardCharsets.ISO_8859_1)
          val text = String(chunkData, nullIdx + 1, chunkData.size - nullIdx - 1, StandardCharsets.ISO_8859_1)
          results[key] = text
        }
      } else if (type == "zTXt") {
        val nullIdx = chunkData.indexOf(0.toByte())
        if (nullIdx > 0 && nullIdx + 2 < chunkData.size) {
          val key = String(chunkData, 0, nullIdx, StandardCharsets.ISO_8859_1)
          val decompressed = decompressZlib(chunkData, nullIdx + 2, chunkData.size - (nullIdx + 2))
          if (decompressed != null) {
            results[key] = decompressed
          }
        }
      } else if (type == "iTXt") {
        val nullIdx = chunkData.indexOf(0.toByte())
        if (nullIdx > 0 && nullIdx < chunkData.size) {
          val key = String(chunkData, 0, nullIdx, StandardCharsets.UTF_8)
          val text = String(chunkData, nullIdx + 1, chunkData.size - nullIdx - 1, StandardCharsets.UTF_8)
          results[key] = text
        }
      }
      pos += 8 + length + 4 // skip length, type, data, crc
    }
    return results
  }

  private fun decompressZlib(data: ByteArray, offset: Int, length: Int): String? {
    return try {
      val inflater = Inflater()
      inflater.setInput(data, offset, length)
      val buffer = ByteArray(64 * 1024)
      var total = 0
      val out = StringBuilder()
      while (!inflater.finished() && total < 1024 * 1024) {
        val count = inflater.inflate(buffer)
        if (count == 0) break
        out.append(String(buffer, 0, count, StandardCharsets.UTF_8))
        total += count
      }
      inflater.end()
      out.toString()
    } catch (_: Exception) {
      null
    }
  }
}
